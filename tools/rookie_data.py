#!/usr/bin/env python3
"""Generates src/shared/Heist/RookieData.luau from assets/fbx/kit_manifest.json (the Rookie pieces of the art kit).

    python3 tools/rookie_data.py          # write the module
    python3 tools/rookie_data.py --check  # exit 1 when the module is stale (the unit spec checks it too)

The module is pure data in Roblox axes (Y up, the Rookie faces -Z, feet at the origin): the 15 R15 body parts (kit
piece, R15 joint, parent, joint position, size and centre for the block fallback), the faces, the outfit pieces by
slot and variant (attach part + offset from that part's joint), which pieces take a runtime colour, and the
first-person arms with their grips. Heist/Rookie (server) builds characters from it; the client reads it too.
Re-run after an art change to assets/blender/rookie.py (build_asset.py writes the manifest).
"""
import json, pathlib, shutil, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "assets" / "fbx" / "kit_manifest.json"
OUT = ROOT / "src" / "shared" / "Heist" / "RookieData.luau"

ORDER = ["LowerTorso", "UpperTorso", "Head", "RightUpperArm", "RightLowerArm", "RightHand", "LeftUpperArm",
         "LeftLowerArm", "LeftHand", "RightUpperLeg", "RightLowerLeg", "RightFoot", "LeftUpperLeg", "LeftLowerLeg",
         "LeftFoot"]


def num(x):
    x = round(float(x), 3) + 0.0
    return str(int(x)) if x == int(x) else repr(x)


def vec(v):
    return "{ " + ", ".join(num(x) for x in v) + " }"


def tint_of(p):
    t = (p.get("tint") or "").lower()
    if t.startswith("crew"):
        return "crew"
    if t.startswith("glove"):
        return "gloves"
    return None


def source():
    parts = json.loads(MANIFEST.read_text())["parts"]
    rk = {n: p for n, p in parts.items() if n.startswith("Rookie")}
    out = ["--!strict",
           "-- GENERATED by tools/rookie_data.py from assets/fbx/kit_manifest.json. Do not edit: re-run it after an art",
           "-- change to assets/blender/rookie.py. The Rookie's kit pieces in Roblox axes (Y up, facing -Z, feet at the",
           "-- origin). body: R15 part -> kit piece, joint (its pivot), parent, size and centre (the block fallback).",
           "-- attach: outfit pieces and faces weld to `part` with their pivot at that part's pivot + `offset`.",
           "-- tint: \"crew\" (seat hue) or \"gloves\" (Config.Rookie.GLOVES). viewmodel: first-person arms (pivot = elbow).",
           "-- hands: first-person gloves with fingers by side, chain order; offset = the hinge from the wrist (rest pose).",
           "-- fpArms: the dedicated first-person arms by side (grip space: fingers -Z, the back of the hand +Y, full size).",
           "-- fpHands: FP HANDS v2, the skinned gloves and their forearm pieces (grip space, authored size; meshes at scale).",
           "",
           "return {"]
    out.append("\tbody = {")
    for name in ORDER:
        p = rk["Rookie_" + name]
        j = p["joint"]
        parent = (j["parent"] or "").replace("Rookie_", "")
        lo, hi, o = p["boundsMin"], p["boundsMax"], p["origin"]
        centre = [o[i] + (lo[i] + hi[i]) / 2 for i in range(3)]
        out.append(f'\t\t{{ part = "{name}", piece = "Rookie_{name}", joint = "{j["name"]}", parent = '
                   + (f'"{parent}"' if parent else "nil")
                   + f", origin = {vec(o)}, size = {vec(p['size'])}, centre = {vec(centre)} }},")
    out.append("\t},")
    faces = {p["face"]: n for n, p in rk.items() if p.get("face")}
    out.append("\tfaces = {")
    for mood in ("idle", "smug", "shocked", "busted"):
        out.append(f'\t\t{mood} = "{faces[mood]}",')
    out.append("\t},")
    groups = {}
    for n, p in sorted(rk.items()):
        groups.setdefault(p["model"], []).append(n)
    out.append("\tgroups = {")
    for g, names in sorted(groups.items()):
        out.append(f"\t\t{g} = {{ " + ", ".join(f'"{n}"' for n in names) + " },")
    out.append("\t},")
    out.append("\tattach = {")
    for n, p in sorted(rk.items()):
        a = p.get("attach")
        if a:
            out.append(f'\t\t{n} = {{ part = "{a["part"]}", offset = {vec(a["offset"])} }},')
    out.append("\t},")
    slots = {}
    for n, p in sorted(rk.items()):
        if p.get("slot"):
            slots.setdefault(p["slot"], {}).setdefault(p["variant"], []).append(n)
    out.append("\toutfit = {")
    for slot in sorted(slots):
        out.append(f"\t\t{slot} = {{")
        for variant in sorted(slots[slot]):
            out.append(f"\t\t\t{variant} = {{ " + ", ".join(f'"{n}"' for n in slots[slot][variant]) + " },")
        out.append("\t\t},")
    out.append("\t},")
    out.append("\ttint = {")
    for n, p in sorted(rk.items()):
        t = tint_of(p)
        if t:
            key = n.replace("Rookie_", "") if p.get("joint") else n
            out.append(f'\t\t{key} = "{t}",')
    out.append("\t},")
    # first-person gloves with fingers (Rookie_Hands): per side, the segments in chain order (parent before child)
    segs = {}
    for n, p in sorted(rk.items()):
        f = p.get("finger")
        if f:
            segs.setdefault(f["side"], []).append((n, f, p["attach"]["offset"]))
    order = ["Palm", "Index1", "Index2", "Fingers1", "Fingers2", "Thumb1", "Thumb2"]
    out.append("\thands = {")
    for side in sorted(segs):
        out.append(f"\t\t{side} = {{")
        for n, f, off in sorted(segs[side], key=lambda r: order.index(r[1]["name"]) if r[1]["name"] in order else 99):
            parent = f'"{f["parent"]}"' if f.get("parent") else "nil"
            out.append(f'\t\t\t{{ piece = "{n}", joint = "{f["name"]}", parent = {parent}, offset = {vec(off)} }},')
        out.append("\t\t},")
    out.append("\t},")
    # the dedicated first-person arms (Rookie_FPArms): per side, the pieces in chain order (palm, fingers base to tip,
    # the thumb, the cuffs, then the forearm frame's pieces); hinge / look / up in grip space, centre = the piece's
    # box centre from its pivot (the MeshPart CFrame), size = the authored MeshPart size
    fp = {}
    for n, p in rk.items():
        f = p.get("fp")
        if f:
            fp.setdefault(f["side"], []).append((n, f, p))
    joint_order = ["Palm"] + [f"{a}{i}" for a in ("Index", "Middle", "Ring", "Pinky", "Thumb") for i in (1, 2, 3)] + \
        ["CuffKnit", "CuffLeather", "Sleeve", "Stripes", "Block", "Watch"]
    out.append("\tfpArms = {")
    for side in sorted(fp):
        out.append(f"\t\t{side} = {{")
        for n, f, p in sorted(fp[side], key=lambda r: joint_order.index(r[1]["joint"])):
            lo, hi = p["boundsMin"], p["boundsMax"]
            centre = [(lo[i] + hi[i]) / 2 for i in range(3)]
            fields = [f'piece = "{n}"', f'joint = "{f["joint"]}"',
                      "parent = " + (f'"{f["parent"]}"' if f.get("parent") else "nil"), f'frame = "{f["frame"]}"',
                      f"hinge = {vec(f['hinge'])}"]
            if f.get("look"):
                fields += [f"look = {vec(f['look'])}", f"up = {vec(f['up'])}"]
            fields += [f"centre = {vec(centre)}", f"size = {vec(p['size'])}"]
            if f.get("slot"):
                fields += [f'slot = "{f["slot"]}"', f'variant = "{f["variant"]}"']
            t = tint_of(p)
            fields.append("tint = " + (f'"{t}"' if t else "nil"))
            fields.append(f"tris = {p['tris']}")
            out.append("\t\t\t{ " + ", ".join(fields) + " },")
        out.append("\t\t},")
    out.append("\t},")
    # FP HANDS v2 (Rookie_FPHands): per side the forearm-frame pieces (the skinned glove first), then `bones`: the
    # glove's Bones in chain order as FpRig entries (Root / Forearm ride the forearm frame, Hand the hand frame, the
    # finger and thumb bones are hinged segments: hinge / look / up in grip space, authored size). The meshes are
    # exported at `scale` (the size the game draws them; it never resizes a skinned mesh).
    v2 = {}
    for n, p in rk.items():
        f = p.get("fp2")
        if f:
            v2.setdefault(f["side"], []).append((n, f, p))
    if v2:
        order2 = ["Glove", "CuffKnit", "CuffLeather", "Sleeve", "Stripes", "Block", "Watch"]
        scale = next(f["scale"] for side in v2 for _n, f, _p in v2[side] if f.get("scale"))
        out.append("\tfpHands = {")
        out.append(f"\t\tscale = {num(scale)},")
        bones = {}
        for side in sorted(v2):
            out.append(f"\t\t{side} = {{")
            for n, f, p in sorted(v2[side], key=lambda r: order2.index(r[1]["joint"])):
                fields = [f'piece = "{n}"', f'joint = "{f["joint"]}"', f'frame = "{f["frame"]}"',
                          f"hinge = {vec(f['hinge'])}", f"centre = {vec(f['centre'])}", f"size = {vec(p['size'])}"]
                if f.get("slot"):
                    fields += [f'slot = "{f["slot"]}"', f'variant = "{f["variant"]}"']
                t = tint_of(p)
                fields.append("tint = " + (f'"{t}"' if t else "nil"))
                if f.get("skinned"):
                    fields.append("skinned = true")
                    bones[side] = f["bones"]
                fields.append(f"tris = {p['tris']}")
                out.append("\t\t\t{ " + ", ".join(fields) + " },")
            out.append("\t\t},")
        out.append("\t\tbones = {")
        for side in sorted(bones):
            out.append(f"\t\t\t{side} = {{")
            for b in bones[side]:
                fields = [f'piece = "{b["bone"]}"', f'joint = "{b["name"]}"']
                if b["name"] in ("Root", "Forearm"):
                    fields += ['frame = "arm"', "parent = nil"]
                elif b["name"] == "Hand":
                    fields += ['frame = "hand"', "parent = nil"]
                else:
                    parent = "Palm" if b["parent"] == "Hand" else b["parent"]
                    fields += ['frame = "hand"', f'parent = "{parent}"', f"look = {vec(b['look'])}",
                               f"up = {vec(b['up'])}"]
                fields += [f"hinge = {vec(b['hinge'])}", "centre = { 0, 0, 0 }", f'boneParent = ' +
                           (f'"{b["parent"]}"' if b["parent"] else "nil")]
                out.append("\t\t\t\t{ " + ", ".join(fields) + " },")
            out.append("\t\t\t},")
        out.append("\t\t},")
        out.append("\t},")
    out.append("\tviewmodel = {")
    for n, p in sorted(rk.items()):
        g = p.get("grip")
        if g:
            side = "LeftArm" if "Left" in n else "RightArm"
            out.append(f'\t\t{side} = {{ piece = "{n}", grip = "{g["name"]}", gripOffset = {vec(g["offset"])} }},')
    out.append("\t},")
    out.append("}")
    return "\n".join(out) + "\n"


def formatted(src):
    """StyLua's form of the module (the repo's stylua.toml), so --check matches a formatted file."""
    if not shutil.which("stylua"):
        return src
    r = subprocess.run(["stylua", "--stdin-filepath", str(OUT), "-"], input=src, capture_output=True, text=True,
                       cwd=ROOT, check=True)
    return r.stdout


def main(argv):
    src = formatted(source())
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text() == src
        print("RookieData up to date" if ok else "RookieData is stale: run python3 tools/rookie_data.py")
        return 0 if ok else 1
    OUT.write_text(src)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
