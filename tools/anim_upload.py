#!/usr/bin/env python3
"""Upload Lune-written KeyframeSequence .rbxm files as Open Cloud **Animation** assets (PLAN_STEAM_PLUS
§4.4 A3), with the multipart + operation pattern of tools/kit_upload.py.

  lune run tools/anim_spike.luau build/anim_spike.rbxm
  python3 tools/anim_upload.py build/anim_spike.rbxm          # one file: prints the asset id or the error

  lune run tools/clone_clips.luau build/clips                 # the clone pose clips (from ClonePose)
  python3 tools/anim_upload.py --clips build/clips            # uploads new or changed EH_Clone_*.rbxm and
                                                              # regenerates src/shared/Heist/CloneClips.luau

Ids go to assets/anim_ids.json ({stem: {assetId, sha256, moderation}}); a file whose hash matches is skipped.
The engine checks are in tests/clone_engine.luau. Key: in a Claude cloud session the network proxy injects
it (any placeholder works); locally set ROBLOX_API_KEY. The assets must belong to the experience owner, or
the game cannot play them.
"""

import json
import os
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import kit_upload as K  # noqa: E402  (multipart, call, wait_operation, CREATOR)

IDS = K.ROOT / "assets/anim_ids.json"
CLIPS_LUAU = K.ROOT / "src/shared/Heist/CloneClips.luau"
CLIP_PREFIX = "EH_Clone_"


def upload(key: str, path: pathlib.Path) -> dict:
    request = {
        "assetType": "Animation",
        "displayName": ("EH " + path.stem)[:50],
        "description": f"Heist Yourself animation: {path.name} (sha256 {K.sha256(path)[:16]})",
        "creationContext": {"creator": K.CREATOR},
    }
    body, form_type = K.multipart([
        ("request", None, "application/json", json.dumps(request).encode()),
        ("fileContent", path.name, "model/x-rbxm", path.read_bytes()),
    ])
    op = K.call("POST", f"{K.API}/assets", key, body, form_type)
    if "path" not in op:
        raise RuntimeError("no operation: " + json.dumps(op)[:800])
    resp = K.wait_operation(key, op["path"])
    if not resp.get("assetId"):
        raise RuntimeError("operation finished without an assetId: " + json.dumps(resp)[:800])
    return {
        "assetId": int(resp["assetId"]),
        "sha256": K.sha256(path),
        "moderation": (resp.get("moderationResult") or {}).get("moderationState"),
    }


def clips_source(ids: dict) -> str:
    rows = []
    for stem in sorted(ids):
        if stem.startswith(CLIP_PREFIX):
            rows.append(f'\t{stem[len(CLIP_PREFIX):]} = "rbxassetid://{ids[stem]["assetId"]}",')
    return "\n".join([
        "--!strict",
        "-- GENERATED by tools/anim_upload.py --clips: do not edit. The clone's custom poses (Shared/Heist/ClonePose)",
        "-- baked by tools/clone_clips.luau and uploaded as Open Cloud Animation assets; Heist/Rigs plays them at",
        "-- Action priority over the walk / idle clips (PLAN_STEAM_PLUS §4.4 A3).",
        "",
        "local CloneClips: { [string]: string } = {",
        *rows,
        "}",
        "",
        "return table.freeze(CloneClips)",
        "",
    ])


def main() -> int:
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        return 2
    key = os.environ.get("ROBLOX_API_KEY", "proxy-injected")
    ids = K.load_json(IDS, {})
    if args[0] == "--clips":
        folder = pathlib.Path(args[1] if len(args) > 1 else "build/clips").resolve()
        files = sorted(folder.glob(CLIP_PREFIX + "*.rbxm"))
    else:
        folder = None
        files = [pathlib.Path(args[0]).resolve()]
    failed = 0
    for path in files:
        old = ids.get(path.stem)
        if old and old.get("sha256") == K.sha256(path):
            print(f"  same  {path.stem} -> {old['assetId']}")
            continue
        try:
            row = upload(key, path)
        except (K.ScopeError, RuntimeError) as e:
            print(f"UPLOAD REFUSED {path.name}: {str(e)[:2000]}")
            failed += 1
            continue
        if old:
            row["history"] = old.get("history", []) + [old["assetId"]]
        ids[path.stem] = row
        IDS.write_text(json.dumps(ids, indent=2, sort_keys=True) + "\n")
        print(f"  ACCEPTED {path.stem} -> Animation {row['assetId']} ({row['moderation']})")
    if folder is not None:
        CLIPS_LUAU.write_text(clips_source(ids))
        print("wrote", CLIPS_LUAU.relative_to(K.ROOT))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
